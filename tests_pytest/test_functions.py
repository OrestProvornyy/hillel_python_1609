def triangle_are(a, b, c):
    # Перевірка, чи можна утворити трикутник із заданими сторонами
    if a + b > c and a + c > b and b + c > a:
        # Обчислюємо півпериметр
        s = (a + b + c) / 2
        # Обчислюємо площу за формулою Герона
        area = (s * (s - a) * (s - b) * (s - c)) ** 0.5
        return area
    else:
        return "Не трикутник"
